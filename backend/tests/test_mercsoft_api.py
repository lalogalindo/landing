"""MercSoft API backend tests."""
import os
import time
import pytest
import requests
from pymongo import MongoClient

BASE_URL = os.environ.get("REACT_APP_BACKEND_URL", "http://localhost:3000").rstrip("/")
API = f"{BASE_URL}/api"

MONGO_URL = os.environ.get("MONGO_URL", "mongodb://localhost:27017")
DB_NAME = os.environ.get("DB_NAME", "test_database")


@pytest.fixture(scope="module")
def db():
    cli = MongoClient(MONGO_URL)
    return cli[DB_NAME]


# ========== /api/ root ==========
def test_root_status():
    r = requests.get(f"{API}/", timeout=15)
    assert r.status_code == 200
    data = r.json()
    assert data.get("status") == "ok"
    assert "MercSoft" in data.get("message", "")


# ========== /api/config ==========
def test_config_returns_phone_and_email():
    r = requests.get(f"{API}/config", timeout=15)
    assert r.status_code == 200
    data = r.json()
    assert data.get("contact_phone") == "2221401900"
    assert data.get("contact_email") == "lalogalindo@gmail.com"



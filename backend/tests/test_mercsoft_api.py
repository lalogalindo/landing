# ========== /api/contact happy path ==========
# NOTE: Google's test secret only accepts tokens minted by the test site-key in
# a real browser (it returns invalid-input-response for arbitrary strings).
# So the full success path cannot be verified with pure HTTP. The UI test
# (Playwright) covers it. We additionally assert here that the backend rejects
# bogus tokens with HTTP 400 (reCAPTCHA verification failed) -- this validates
# the verify_recaptcha → 400 branch.
def test_contact_bogus_recaptcha_returns_400(db):
    payload = {
        "name": "TEST_Backend Tester",
        "email": "TEST_tester@example.com",
        "company": "TEST_Co",
        "subject": "TEST_Automated backend test",
        "message": "TEST_This submission was generated by automated tests.",
        "recaptcha_token": "bogus-token-not-from-real-widget",
        "locale": "en",
    }
    r = requests.post(f"{API}/contact", json=payload, timeout=45)
    assert r.status_code == 400
    assert "reCAPTCHA" in r.text or "recaptcha" in r.text.lower()


